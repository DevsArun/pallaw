/**
 * The canonical OUTPUT schema. Read from sample_questions.csv so the export
 * always matches exactly the columns your app imports. Falls back to a known
 * MCQ schema if the file is missing.
 *
 * @return string[]
 */
function canonical_columns(): array
{
    static $cols = null;
    if ($cols !== null) {
        return $cols;
    }
    $fallback = ['question_text', 'option_a', 'option_b', 'option_c', 'option_d', 'correct_option', 'explanation', 'difficulty'];
    $file = __DIR__ . '/../sample_questions.csv';
    if (is_file($file) && ($fh = fopen($file, 'r'))) {
        $header = fgetcsv($fh, 0, ',', '"', '\\');
        fclose($fh);
        if (is_array($header)) {
            $clean = [];
            foreach ($header as $i => $h) {
                $h = trim((string) $h);
                if ($i === 0) {
                    $h = preg_replace('/^\xEF\xBB\xBF/', '', $h); // strip BOM
                }
                if ($h !== '') {
                    $clean[] = $h;
                }
            }
            if (count($clean) > 1) {
                return $cols = $clean;
            }
        }
    }
    return $cols = $fallback;
}

/** Default values for Groq settings managed by the UI. */
function default_settings(): array
{
    return [
        'groq_api_key' => '',
        'groq_model'   => DEFAULT_MODEL,
    ];
}

/** Load locally-saved settings (from settings.local.php). */
function load_local_settings(): array
{
    if (is_file(SETTINGS_FILE)) {
        $data = include SETTINGS_FILE;
        if (is_array($data)) {
            return $data;
        }
    }
    return [];
}

/** Resolve a Groq setting (env > local file > default). */
function setting(string $key, $fallback = null)
{
    static $local = null;
    if ($local === null) {
        $local = load_local_settings();
    }
    $env = getenv(strtoupper($key));
    if ($env !== false && $env !== '') {
        return $env;
    }
    if (array_key_exists($key, $local) && $local[$key] !== '') {
        return $local[$key];
    }
    $defaults = default_settings();
    return $defaults[$key] ?? $fallback;
}

/** Persist Groq settings to settings.local.php. */
function save_settings(array $values): bool
{
    $allowed = array_keys(default_settings());
    $clean   = [];
    foreach ($allowed as $k) {
        if (array_key_exists($k, $values)) {
            $clean[$k] = (string) $values[$k];
        }
    }
    $merged = array_merge(load_local_settings(), $clean);
    $php = "<?php\n// Auto-generated by the Settings page. Do not commit.\nreturn "
        . var_export($merged, true) . ";\n";
    return @file_put_contents(SETTINGS_FILE, $php) !== false;
}

/** Send a JSON response and stop. */
function json_response(int $status, array $payload): void
{
    http_response_code($status);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($payload, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

/** Read and decode a JSON request body. */
function read_json_body(): array
{
    $raw = file_get_contents('php://input');
    if ($raw === false || $raw === '') {
        return [];
    }
    $data = json_decode($raw, true);
    return is_array($data) ? $data : [];
}
